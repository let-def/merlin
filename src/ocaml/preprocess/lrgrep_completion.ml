(* Runtime support for the syntactic completion generated by
   [lrgrep completion], see the interface. *)

module type PARSER = sig
  type token
  module MenhirInterpreter : MenhirLib.IncrementalEngine.EVERYTHING
    with type token = token
  module Tables : MenhirLib.TableFormat.TABLES
    with type token = token
end

type automaton = {
  links : Lrgrep_runtime.Sparse_table.t;
  cell_nonterminal : int -> int;
  cell_row : int -> int;
  cell_default : int -> int;
  initial : int;
  action_clause : int -> int;
  action_spawns : int -> int;
  spawn_cell : int -> int;
  spawn_depth : int -> int;
}

module type TABLES = sig
  type symbol
  type segment
  val symbol_of_int : int -> symbol
  val int_of_symbol : symbol -> int
  val segment_of_int : int -> segment
  val int_of_segment : segment -> int
  val automaton : automaton
  val groups : string
  val group_offsets : int -> int
  val clause_groups : int -> int
  val clause_offsets : int -> int
  val terminals : int
  val productions : int -> int
  val production_offsets : int -> int
  val tree_production : int -> int
  val tree_parent : int -> int
  val tree_offsets : int -> int
  val surface_names : string array
  val surface_omitted : string
  val surface_annotated : string
  val surface_display : string array
  val branch_count : int
  val branch_rule : int -> int
  val branch_producers : int -> int
  val branch_offsets : int -> int
  val path_branch : int -> int
  val path_index : int -> int
  val path_offsets : int -> int
  val ngram_length : int
  val ngram_classes : int
  val ngram_sets : int
  val ngram_class : int -> int
  val ngram_set_base : int -> int
  val ngram_set_offsets : int -> int
  val ngram_set_delta : string
  val ngram_pairs : Lrgrep_runtime.Sparse_table.t
  val ngram_pair_row : int -> int
  val trigram_rows : int
  val trigram_row_offsets : int -> int
  val trigram_keysets : int
  val trigram_groups : int -> int
  val trigram_keys_size : int
  val trigram_keys : string
end

type suggestion = {
  depth : int;
  state : int;
  terminal : int;
  derivation : (int * int) list;
}

type piece =
  | Symbol of string
  | Optional of piece list

(* The value of [row] and [col] in [table], or [default] shifted by one *)
let lookup_opt table row default col =
  match Lrgrep_runtime.Sparse_table.lookup table row col with
  | Some _ as v -> v
  | None -> if default = 0 then None else Some (default - 1)

(* [insertion short long] is [Some (a @ [Optional x] @ b)] if [short] is
   [a @ b] and [long] is [a @ x @ b], [x] not empty *)
let insertion short long =
  let n = List.length short and m = List.length long in
  if m <= n then None else
    let short = Array.of_list short and long = Array.of_list long in
    let prefix = ref 0 in
    while !prefix < n && short.(!prefix) = long.(!prefix) do incr prefix done;
    let suffix = ref 0 in
    while !suffix < n - !prefix && short.(n - 1 - !suffix) = long.(m - 1 - !suffix) do
      incr suffix
    done;
    if !prefix + !suffix < n then None else
      let sub a i j = List.map (fun s -> Symbol s) (Array.to_list (Array.sub a i (j - i))) in
      Some (sub long 0 !prefix @ [Optional (sub long !prefix (m - !suffix))]
            @ sub long (m - !suffix) m)

module Make (P : PARSER) (T : TABLES) = struct
  module I = P.MenhirInterpreter
  module ET = MenhirLib.TableInterpreter.MakeEngineTable (P.Tables)
  open T

  type nonrec suggestion = suggestion = {
    depth : int;
    state : int;
    terminal : int;
    derivation : (int * int) list;
  }

  type nonrec piece = piece =
    | Symbol of string
    | Optional of piece list

  let terminals = T.terminals

  let rhs_length p = production_offsets (p + 1) - production_offsets p - 1
  let rhs p i = productions (production_offsets p + 1 + i)

  (* The automaton of pending reductions *)

  (* The action of a cell and a state, through the goto transition of the
     state on the non-terminal of the cell (the initial cell has none and
     applies to the state itself). *)
  let action_of cell state =
    let t = automaton in
    let target = match t.cell_nonterminal cell with
      | 0 -> Some state
      | nt -> ET.maybe_goto_nt state (nt - 1)
    in
    match target with
    | None -> None
    | Some target -> lookup_opt t.links (t.cell_row cell) (t.cell_default cell) target

  (* [run env f] calls [f ~clause ~depth] for each clause reached, [depth]
     being the number of frames above the one whose goto transition reached
     it. A clause can be reached more than once. *)
  let run env f =
    let t = automaton in
    (* [later]: the cells pending below the current frame, with their depth
       relative to it. *)
    let rec frame env ~depth ~now later =
      let state = I.current_state_number env in
      let applied = ref [] and later = ref later in
      let rec action e =
        let clause = t.action_clause e in
        if clause > 0 then f ~clause:(clause - 1) ~depth;
        for i = t.action_spawns e to t.action_spawns (e + 1) - 1 do
          let cell = t.spawn_cell i in
          match t.spawn_depth i with
          | 0 -> apply cell
          | d -> later := (cell, d) :: !later
        done
      and apply cell =
        if not (List.mem cell !applied) then (
          applied := cell :: !applied;
          match action_of cell state with
          | Some e -> action e
          | None -> ()
        )
      in
      List.iter apply now;
      match List.sort_uniq compare !later with
      | [] -> ()
      | later ->
        match I.pop env with
        | None -> ()
        | Some env ->
          let now = List.filter_map (fun (c, d) -> if d = 1 then Some c else None) later in
          let later = List.filter_map (fun (c, d) -> if d > 1 then Some (c, d - 1) else None) later in
          frame env ~depth:(depth + 1) ~now later
    in
    frame env ~depth:0 ~now:[t.initial] []

  (* Suggestions *)

  (* The kernel items of a state, sorted by production and position. The
     inspection API has no function from numbers to states, but the numbers
     of the table are valid states; likewise for the productions, whose
     number [I.production_index] rejects for the start productions (the
     kernel of an initial state). *)
  let kernel state =
    I.items (Obj.magic state : _ I.lr1state)
    |> List.map (fun (prod, pos) -> ((Obj.magic prod : int), pos))
    |> List.sort compare

  (* The suggestions of a state, with their terminal and derivation, in the
     order of the generator: for each kernel item, the item itself if its
     next symbol is a terminal, or the productions of the derivation tree
     of its next symbol that start with a terminal, except the ones already
     seen. *)
  let table = Hashtbl.create 7

  let suggestions state =
    match Hashtbl.find_opt table state with
    | Some s -> s
    | None ->
      let seen = Hashtbl.create 7 and result = ref [] in
      List.iter (fun (p, pos as item) ->
          if pos < rhs_length p then
            let sym = rhs p pos in
            if sym < terminals then
              result := (sym, [item]) :: !result
            else
              let first = tree_offsets (sym - terminals) in
              for e = first to tree_offsets (sym - terminals + 1) - 1 do
                let q = tree_production e in
                if rhs_length q > 0 && rhs q 0 < terminals
                   && not (Hashtbl.mem seen q) then begin
                  Hashtbl.add seen q ();
                  let rec chain e acc =
                    let acc = (tree_production e, 0) :: acc in
                    match tree_parent e with
                    | 0 -> acc
                    | parent -> chain (first + parent - 1) acc
                  in
                  result := (rhs q 0, item :: chain e []) :: !result
                end
              done
        ) (kernel state);
      let s = Array.of_list (List.rev !result) in
      Hashtbl.add table state s;
      s

  (* [iter_groups f clause] calls [f state terminal derivation] for each
     suggestion of the groups of [clause]. *)
  let iter_groups f clause =
    for i = clause_offsets clause to clause_offsets (clause + 1) - 1 do
      let group = group_offsets (clause_groups i) in
      let state = String.get_uint16_be groups group in
      let length = String.get_uint8 groups (group + 2) in
      let suggestions = suggestions state in
      for j = 0 to 8 * length - 1 do
        if String.get_uint8 groups (group + 3 + j / 8) land (1 lsl (j mod 8)) <> 0 then
          let terminal, derivation = suggestions.(j) in
          f state terminal derivation
      done
    done

  let complete env =
    let seen = Hashtbl.create 7 and result = ref [] in
    run env (fun ~clause ~depth ->
        iter_groups (fun state terminal derivation ->
            let key = (state, List.nth derivation (List.length derivation - 1)) in
            if not (Hashtbl.mem seen key) then (
              Hashtbl.add seen key ();
              result := {depth; state; terminal; derivation} :: !result))
          clause);
    List.rev !result

  (* Suggestions in the surface grammar *)

  (* The pieces of the continuation from item [(p, pos)], as pairs of a
     branch and a position: from the symbol at [pos] ([~leaf]) or after it,
     the producers in the innermost branch of inlining, then those after
     the inlined producer at each enclosing level. *)
  let surface_rest ~leaf (p, pos) =
    let i = production_offsets p + 1 + pos in
    let last = path_offsets (i + 1) in
    List.init (last - path_offsets i) (fun d ->
        let j = last - 1 - d in
        (path_branch j, path_index j + if leaf && d = 0 then 0 else 1))

  let pieces s =
    match List.rev s.derivation with
    | [] -> []
    | last :: outer ->
      surface_rest ~leaf:true last @ List.concat_map (surface_rest ~leaf:false) outer

  let surface_symbols s =
    List.concat_map (fun (b, from) ->
        let first = branch_offsets b + from in
        List.init (branch_offsets (b + 1) - first) (fun k -> branch_producers (first + k)))
      (pieces s)

  let segments s =
    List.filter_map (fun (b, from) ->
        let first = branch_offsets b + from in
        if first < branch_offsets (b + 1) then Some (segment_of_int first) else None)
      (pieces s)

  let symbols s = List.map symbol_of_int (surface_symbols s)

  (* The branch of a segment: the last branch starting at or before it *)
  let segment_branch seg =
    let i = int_of_segment seg in
    let rec search lo hi =
      if hi - lo <= 1 then lo else
        let m = (lo + hi) / 2 in
        if branch_offsets m <= i then search m hi else search lo m
    in
    search 0 branch_count

  let segment_symbols seg =
    let i = int_of_segment seg in
    Array.init (branch_offsets (segment_branch seg + 1) - i)
      (fun k -> symbol_of_int (branch_producers (i + k)))

  let segment_rule seg = symbol_of_int (branch_rule (segment_branch seg))

  let segment_item seg =
    let b = segment_branch seg in
    (Array.init (branch_offsets (b + 1) - branch_offsets b)
       (fun k -> symbol_of_int (branch_producers (branch_offsets b + k))),
     int_of_segment seg - branch_offsets b)

  let symbol_name sym = surface_names.(int_of_symbol sym)
  let is_terminal sym = int_of_symbol sym < terminals
  let terminal_symbol t = symbol_of_int t

  let surface_continuation s = List.map (fun n -> surface_names.(n)) (surface_symbols s)

  let omitted n = surface_omitted.[n] = '1'

  (* One of the items of the derivation is inside an omitted symbol at some
     level of inlining *)
  let is_omitted s =
    List.exists (fun (p, pos) ->
        let i = production_offsets p + 1 + pos in
        let rec loop j =
          j < path_offsets (i + 1) &&
          (omitted (branch_producers (branch_offsets (path_branch j) + path_index j))
           || loop (j + 1))
        in
        loop (path_offsets i))
      s.derivation

  let symbol_display sym = surface_display.(int_of_symbol sym)
  let symbol_omitted sym = omitted (int_of_symbol sym)

  let symbol_annotation sym =
    let n = int_of_symbol sym in
    if surface_annotated.[n] = '1' then Some surface_display.(n) else None

  let segment_display ?(symbol = symbol_display) seg =
    List.filter_map (fun sym -> if symbol_omitted sym then None else Some (symbol sym))
      (Array.to_list (segment_symbols seg))

  let display_continuation s =
    List.filter_map (fun n -> if omitted n then None else Some surface_display.(n))
      (surface_symbols s)

  let complete_by_continuation env =
    let groups = Hashtbl.create 7 and order = ref [] in
    List.iter (fun s ->
        if not (is_omitted s) then
          let c = display_continuation s in
          match Hashtbl.find_opt groups c with
          | Some l -> l := s :: !l
          | None -> Hashtbl.add groups c (ref [s]); order := c :: !order)
      (complete env);
    let key s = (s.depth, List.length s.derivation) in
    let sort l = List.stable_sort (fun s1 s2 -> compare (key s1) (key s2)) l in
    let groups =
      List.rev_map (fun c -> (c, sort (List.rev !(Hashtbl.find groups c)))) !order
      |> List.stable_sort (fun (_, l1) (_, l2) ->
          let progress l = snd (List.hd (List.hd l).derivation) in
          compare ((List.hd l2).depth, progress l2) ((List.hd l1).depth, progress l1))
    in
    (* Merge each continuation with the first one, at the same depth, that
       it extends or that extends it by a segment *)
    let merged = Array.make (List.length groups) false in
    let groups = Array.of_list groups in
    let result = ref [] in
    Array.iteri (fun i (c, l) ->
        if not merged.(i) then begin
          let depth = (List.hd l).depth in
          let found = ref None in
          Array.iteri (fun j (c', l') ->
              if !found = None && j > i && not merged.(j) && (List.hd l').depth = depth then
                match insertion c c', insertion c' c with
                | Some pieces, _ | None, Some pieces -> found := Some (j, pieces, l')
                | None, None -> ())
            groups;
          match !found with
          | Some (j, pieces, l') ->
            merged.(j) <- true;
            result := (pieces, sort (l @ l')) :: !result
          | None -> result := (List.map (fun s -> Symbol s) c, l) :: !result
        end)
      groups;
    List.rev !result

  (* Transitions *)

  let transition state symbol =
    if symbol < terminals
    then ET.maybe_shift_t state symbol
    else ET.maybe_goto_nt state (symbol - terminals)

  (* The targets of the transitions on the remaining symbols of each item of
     the derivation, from the last one, up to a missing transition *)
  let visited s =
    let rec items state = function
      | [] -> []
      | (p, pos) :: rest ->
        let rec walk state i =
          if i = rhs_length p then items s.state rest else
            match transition state (rhs p i) with
            | None -> []
            | Some state -> state :: walk state (i + 1)
        in
        walk state pos
    in
    items s.state (List.rev s.derivation)

  (* The sets of states of the n-grams, decoded on demand as bitsets of
     classes *)
  let ngram_set_size = (ngram_classes + 7) / 8
  let ngram_decoded = Array.make ngram_sets Bytes.empty

  let rec ngram_bits set =
    let bits = ngram_decoded.(set) in
    if Bytes.length bits > 0 then bits else begin
      let bits = match ngram_set_base set with
        | 0 -> Bytes.make ngram_set_size '\000'
        | base -> Bytes.copy (ngram_bits (base - 1))
      in
      let i = ref (ngram_set_offsets set) and last = ref (-1) in
      while !i < ngram_set_offsets (set + 1) do
        let rec gap shift =
          let b = Char.code ngram_set_delta.[!i] in
          incr i;
          if b < 128 then b lsl shift else (b land 127) lsl shift lor gap (shift + 7)
        in
        let c = !last + 1 + gap 0 in
        last := c;
        Bytes.set_uint8 bits (c / 8) (Bytes.get_uint8 bits (c / 8) lxor (1 lsl (c mod 8)))
      done;
      ngram_decoded.(set) <- bits;
      bits
    end

  let in_set set state =
    let c = ngram_class state in
    c < ngram_classes &&
    Bytes.get_uint8 (ngram_bits set) (c / 8) land (1 lsl (c mod 8)) <> 0

  (* The entry of the pair [t0 t1]: its set and its row of exceptions *)
  let ngram_pair t0 t1 =
    match Lrgrep_runtime.Sparse_table.lookup ngram_pairs (ngram_pair_row t1) t0 with
    | None -> None
    | Some v -> Some (v / trigram_rows, v mod trigram_rows)

  let bigram t0 t1 = Option.map fst (ngram_pair t0 t1)

  let trigram t0 t1 t2 =
    match ngram_pair t0 t1 with
    | None -> None
    | Some (set, 0) -> Some set
    | Some (set, row) ->
      let rec loop i =
        if i = trigram_row_offsets row then Some set else
          let g = trigram_groups i in
          let k = trigram_keys_size * (g mod trigram_keysets) + t2 / 8 in
          if Char.code trigram_keys.[k] land (1 lsl (t2 mod 8)) <> 0
          then Some (g / trigram_keysets)
          else loop (i + 1)
      in
      loop (trigram_row_offsets (row - 1))

  let distance suffix =
    let suffix = Array.of_list suffix in
    let n = ngram_length in
    let sets = Array.init (max 0 (Array.length suffix - n + 1)) (fun i ->
        if n = 2
        then bigram suffix.(i) suffix.(i + 1)
        else trigram suffix.(i) suffix.(i + 1) suffix.(i + 2)) in
    fun s ->
      let best = ref max_int in
      List.iteri (fun j state ->
          let i = ref 0 in
          while !i < Array.length sets && !i + j < !best do
            (match sets.(!i) with
             | Some set when in_set set state -> best := !i + j
             | _ -> ());
            incr i
          done)
        (visited s);
      !best

  let rank ~suffix env =
    let distance = distance (List.map P.Tables.token2terminal suffix) in
    complete_by_continuation env
    |> List.map (fun (c, l) ->
        (List.fold_left (fun acc s -> min acc (distance s)) max_int l, (c, l)))
    |> List.stable_sort (fun (d1, _) (d2, _) -> compare d1 d2)
    |> List.map snd
end
