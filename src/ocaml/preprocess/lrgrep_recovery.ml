(* Runtime support for the error recovery generated by [lrgrep recover].

   The generated module provides the tables of the strategies of a grammar
   (see [TABLES]) and instantiates [Make] with them and the parser, which
   must be generated by Menhir with [--table --inspection].

   The recovery is driven by a bracket policy, which gives a tree structure
   to the input: brackets inserted in the token stream, meaning that the
   tokens between them should appear roughly in the same node of the
   syntax tree. Normal parsing ignores the brackets. When the parser
   fails, the frames of its stack are related to the spans of the brackets
   by their positions:

   - if the parser accepted tokens in a construct that the brackets had
     closed (an unfinished definition absorbing the next one), the stack is
     cut below the first frame that violates the spans, and the recovery
     resumes from the token where this frame starts;

   - the candidates of the recovery are the configurations reached by the
     strategies, by increasing cost (a Dijkstra search). At each token, the
     cheapest candidate that accepts the next tokens and whose frames are
     consistent with the spans resumes the parse; the cheapest accepting
     one if none is consistent. If no candidate accepts the token, it is
     skipped.

   The search is simulated on the states of the stack: a candidate builds
   the real stack of the parser, running the semantic actions, only when
   it is chosen. *)

(** The parser, generated by Menhir with [--table --inspection]. *)
module type PARSER = sig
  type token
  module MenhirInterpreter : MenhirLib.IncrementalEngine.EVERYTHING
    with type token = token
  module Tables : MenhirLib.TableFormat.TABLES
    with type token = token
end

(** The tables generated by [lrgrep recover]. The symbols are numbered
    terminals first, then non-terminals. *)
module type TABLES = sig
  type 'a env

  (** Shift a symbol with its placeholder value, at a position. *)
  val shift : int -> Lexing.position -> 'a env -> 'a env

  (** The number of terminals. *)
  val terminal_count : int

  (** The length of the right-hand side of a production. *)
  val production_length : int -> int

  (** The tactics: sequences of actions [4 * x + kind], to reduce
      production [x] (kind 0), shift symbol [x] (1), apply tactic [x] (2)
      or accept (3). The actions of tactic [t] are the ones from
      [tactic_offsets t] to [tactic_offsets (t + 1) - 1]. *)
  val tactic_offsets : int -> int
  val tactic_actions : int -> int

  (** The tactic completing the start item of an entrypoint, plus one (0
      for none). *)
  val initial_tactic : int -> int

  (** The strategies of a transition: the state at the top (a row of
      [strategy_lists], through [strategy_row]) and the one below (a
      column) map to a list, a range of strategies. *)
  val strategy_lists : Lrgrep_runtime.Sparse_table.t
  val strategy_row : int -> int
  val strategy_offsets : int -> int
  val strategy_tactic : int -> int
  val strategy_cost : int -> int
  val strategy_total : int -> int

  (** The item completed by a strategy: the non-terminal of its production
      (plus one, 0 for a start production), and its position. *)
  val strategy_lhs : int -> int
  val strategy_pos : int -> int

  (** Merlin's decisions: the depth of a state, its default tactic (plus
      one, 0 for none), and the tactics by state at that depth
      ([merlin_states] standing for the bottom of the stack). *)
  val merlin_depth : int -> int
  val merlin_default : int -> int
  val merlin_states : int
  val merlin_select : Lrgrep_runtime.Sparse_table.t
  val merlin_row : int -> int
end

(** The tokens of a language, for the lexical policy ([Make.lexical]): its
    delimiters, its items (the definitions of a module) and its local
    bindings, which do not depend on the layout. *)
type 'token lexical = {
  delimiters : 'token option -> 'token -> [`Open of int | `Close of int] list;
  (** The roles of a token, given the previous one: the kinds of pairs it
      closes, then opens. *)
  starts_item : 'token -> 'token -> bool;
  (** Whether a token, given the previous one, starts an item: when the
      previous token cannot be followed by it inside an item. *)
  binding : 'token -> [`Let | `In | `Equal | `Other];
  (** The tokens of the local bindings [let ... = ... in ...]: a binding
      waiting for its [in] at the end of an item tells an unfinished
      definition from a missing [in]. *)
}

(* Growable arrays (the library supports OCaml 4.13, without Dynarray) *)
module Vec = struct
  type 'a t = {mutable data : 'a array; mutable length : int}
  let create () = {data = [||]; length = 0}
  let length v = v.length
  let get v i = if i < v.length then v.data.(i) else invalid_arg "Vec.get"
  let set v i x = if i < v.length then v.data.(i) <- x else invalid_arg "Vec.set"
  let add_last v x =
    if v.length = Array.length v.data then
      v.data <- Array.append v.data (Array.make (max 8 v.length) x);
    v.data.(v.length) <- x;
    v.length <- v.length + 1
end

(** {1 Bracket policies}

    They do not depend on the parser, only on its tokens. *)

(** The tokens given to a bracket policy: start position, token, end
    position. *)
type 'token triple = Lexing.position * 'token * Lexing.position

(** A bracket policy: the numbers of brackets opened and closed before
    each token, the closed ones first. It should observe as few tokens as
    needed to produce each pair. *)
type 'token bracket_policy = 'token triple Seq.t -> (int * int) Seq.t

let column (p : Lexing.position) = p.pos_cnum - p.pos_bol

(** The indentation policy: a bracket opens at each line more indented
    than the enclosing ones, and the brackets of the lines more indented
    than a line close before it; the last token closes all of them. *)
let indentation : 'token bracket_policy = fun tokens ->
  let rec go levels line tokens () =
    match tokens () with
    | Seq.Nil -> Seq.Nil
    | Seq.Cons (((p : Lexing.position), _, _), rest) ->
      if (match rest () with Seq.Nil -> true | Seq.Cons _ -> false) then
        Seq.Cons ((0, List.length levels - 1), Seq.empty)
      else if p.pos_lnum = line then Seq.Cons ((0, 0), go levels line rest)
      else
        let col = column p in
        let rec close levels n =
          match levels with
          | l :: (_ :: _ as rest) when col < l -> close rest (n + 1)
          | _ -> (levels, n)
        in
        let levels, closed = close levels 0 in
        if col > List.hd levels
        then Seq.Cons ((1, closed), go (col :: levels) p.pos_lnum rest)
        else Seq.Cons ((0, closed), go levels p.pos_lnum rest)
  in
  go [0] 0 tokens

(** The lexical policy, which does not look at the layout (columns and
    lines), for minified or garbled inputs too, with the tokens of the
    language described by [l].

    - The delimiters are matched over the whole input, with the fewest
      left unmatched: the adjacent matching delimiters first (which keeps
      a minimal matching), in one pass; then a dynamic programming,
      cubic, on the delimiters that remain, a few per error ([limit] of
      them at most, 400; a greedy matching above). The matched pairs are
      spans, the unmatched delimiters are not.
    - With [items] (the default), each item is a span too, from its start
      to the next item start in the same innermost pair. A binding waiting for its [in] at the end of an item comes
      either from a missing [in] or from an unfinished definition,
      followed by a definition read as a local binding: if the binding
      that starts the next item gets its [in] in this next item, an [in]
      is missing, and it does not start an item; otherwise, the last
      binding waiting after a [=], with a [=] of its own, starts an
      item. *)
let lexical ?(items = true) ?(limit = 400) (l : 'token lexical) : 'token bracket_policy = fun tokens ->
  let tokens = Array.of_seq tokens in
  let n = Array.length tokens in
  let tok i = let _, t, _ = tokens.(i) in t in
  let opened = Array.make (n + 1) 0 and closed = Array.make (n + 1) 0 in
  let span a b = if a < b then (opened.(a) <- opened.(a) + 1; closed.(b) <- closed.(b) + 1) in
  let item_start = Array.init n (fun i -> i = 0 || l.starts_item (tok (i - 1)) (tok i)) in
  (* The unfinished definitions *)
  if items then begin
    let starts = List.filter (fun i -> item_start.(i)) (List.init n Fun.id) in
    let starts = Array.of_list (starts @ [n]) in
    (* The bindings left open in the tokens [a] to [b - 1], the one at [a]
       included when [first] *)
    let open_lets ~first a b =
      let stack = ref [] in
      for i = a to b - 1 do
        match l.binding (tok i) with
        | `Let when i > a || first -> stack := i :: !stack
        | `In -> (match !stack with _ :: rest -> stack := rest | [] -> ())
        | _ -> ()
      done;
      !stack
    in
    for c = 0 to Array.length starts - 3 do
      let a = starts.(c) and b = starts.(c + 1) and b' = starts.(c + 2) in
      let pending = open_lets ~first:false a b in
      if pending <> [] && l.binding (tok b) = `Let then begin
        if not (List.mem b (open_lets ~first:true b b')) then
          (* The binding of the next item gets its [in]: a missing [in] *)
          item_start.(b) <- false
        else
          (* An unfinished definition *)
          let has_equal u =
            let rec go i = i < b && (l.binding (tok i) = `Equal || go (i + 1)) in
            go (u + 1)
          in
          match List.find_opt (fun u -> u > 0 && l.binding (tok (u - 1)) = `Equal && has_equal u)
                  pending with
          | Some u -> item_start.(u) <- true
          | None -> ()
      end
    done
  end;
  (* The delimiters: a token and a role *)
  let d = Vec.create () and role = Vec.create () in
  for i = 0 to n - 1 do
    List.iter (fun r -> Vec.add_last d i; Vec.add_last role r)
      (l.delimiters (if i > 0 then Some (tok (i - 1)) else None) (tok i))
  done;
  let m = Vec.length d in
  let kind_open i = match Vec.get role i with `Open k -> Some k | `Close _ -> None in
  let kind_close i = match Vec.get role i with `Close k -> Some k | `Open _ -> None in
  (* Matching the adjacent pairs; the remaining delimiters, in order *)
  let mate = Array.make m (-1) in
  let stack = ref [] in
  for i = 0 to m - 1 do
    match kind_close i, !stack with
    | Some k, j :: rest when kind_open j = Some k -> mate.(i) <- j; mate.(j) <- i; stack := rest
    | _ -> stack := i :: !stack
  done;
  let rest = Array.of_list (List.rev !stack) in
  let r = Array.length rest in
  if r > 0 then begin
    let ko x = kind_open rest.(x) and kc x = kind_close rest.(x) in
    if r <= limit then begin
      (* best.(i).(j): the fewest unmatched among the remaining i..j-1 *)
      let best = Array.make_matrix (r + 1) (r + 1) 0 and choice = Array.make_matrix (r + 1) (r + 1) (-1) in
      for len = 1 to r do
        for i = 0 to r - len do
          let j = i + len in
          let b = ref (1 + best.(i + 1).(j)) and c = ref (-1) in
          (match ko i with
           | Some k ->
             for x = i + 1 to j - 1 do
               if kc x = Some k then begin
                 let v = best.(i + 1).(x) + best.(x + 1).(j) in
                 if v < !b then (b := v; c := x)
               end
             done
           | None -> ());
          best.(i).(j) <- !b; choice.(i).(j) <- !c
        done
      done;
      let rec rebuild i j =
        if i < j then
          match choice.(i).(j) with
          | -1 -> rebuild (i + 1) j
          | x ->
            mate.(rest.(i)) <- rest.(x); mate.(rest.(x)) <- rest.(i);
            rebuild (i + 1) x; rebuild (x + 1) j
      in
      rebuild 0 r
    end else begin
      (* Greedy: a closing delimiter pops the stack down to an opening one
         of its kind, if any *)
      let stack = ref [] in
      Array.iter (fun x ->
          match kind_open x, kind_close x with
          | Some k, _ -> stack := (k, x) :: !stack
          | None, Some k ->
            if List.exists (fun (k', _) -> k = k') !stack then begin
              let rec pop = function
                | (k', y) :: rest when k = k' -> mate.(y) <- x; mate.(x) <- y; rest
                | _ :: rest -> pop rest
                | [] -> []
              in
              stack := pop !stack
            end
          | None, None -> ())
        rest
    end
  end;
  (* The matched pairs, as intervals of tokens, by opening, with their
     kind *)
  let pairs = Vec.create () in
  for x = 0 to m - 1 do
    if mate.(x) > x then
      Vec.add_last pairs (Vec.get d x, Vec.get d mate.(x), Option.get (kind_open x))
  done;
  for p = 0 to Vec.length pairs - 1 do
    let o, c, _ = Vec.get pairs p in span o (c + 1)
  done;
  (* The spans of the items: from an item start to the next one in the
     same innermost pair, or to the end of this pair *)
  if items then begin
    let innermost = Array.make n (-1) in
    let stack = ref [] and next = ref 0 in
    let np = Vec.length pairs in
    for i = 0 to n - 1 do
      while !next < np && (let o, _, _ = Vec.get pairs !next in o < i) do
        stack := !next :: !stack; incr next
      done;
      (* The closing delimiter is in the pair *)
      stack := List.filter (fun p -> let _, c, _ = Vec.get pairs p in c >= i) !stack;
      innermost.(i) <- (match !stack with p :: _ -> p | [] -> -1)
    done;
    let last = Hashtbl.create 16 in
    for i = 0 to n - 1 do
      if item_start.(i) then begin
        let p = innermost.(i) in
        (match Hashtbl.find_opt last p with Some a -> span a i | None -> ());
        Hashtbl.replace last p i
      end
    done;
    Hashtbl.iter (fun p a ->
        span a (if p < 0 then n - 1 else let _, c, _ = Vec.get pairs p in c))
      last
  end;
  Seq.init n (fun i -> (opened.(i), closed.(i)))

module Make (P : PARSER) (T : TABLES with type 'a env := 'a P.MenhirInterpreter.env) = struct
  module I = P.MenhirInterpreter
  open T

  let lookup table row col =
    Lrgrep_runtime.Sparse_table.lookup table row col

  (** {1 Strategies and tactics} *)

  (** A strategy: a tactic, its cost, the total cost of exiting the context
      through it, and the item it completes: the non-terminal produced
      ([-1] for a start production) and the position of the item, the
      number of frames it pops before following the goto transition of the
      non-terminal. *)
  type strategy = {
    tactic : int;
    cost : int;
    total : int;
    lhs : int;
    pos : int;
  }

  (** The strategies of a stack whose top state is [top], and [below] the
      one below it, by increasing total cost. *)
  let strategies_of_states top below =
    match below with
    | None ->
      (match initial_tactic top with
       | 0 -> []
       | tactic -> [{tactic = tactic - 1; cost = 0; total = 0; lhs = -1; pos = 0}])
    | Some below ->
      match lookup strategy_lists (strategy_row top) below with
      | None -> []
      | Some l ->
        List.init (strategy_offsets (l + 1) - strategy_offsets l) (fun i ->
            let s = strategy_offsets l + i in
            {tactic = strategy_tactic s; cost = strategy_cost s;
             total = strategy_total s; lhs = strategy_lhs s - 1;
             pos = strategy_pos s})

  (** The strategies of [env], by increasing total cost. *)
  let strategies env =
    strategies_of_states (I.current_state_number env)
      (Option.map I.current_state_number (I.pop env))

  (** The position of placeholder values: the end of the top of the
      stack. *)
  let position env =
    match I.top env with
    | Some (I.Element (_, _, _, endp)) -> endp
    | None -> Lexing.dummy_pos

  (** Apply a tactic to [env]: [`Env env'], or [`Accept env'] when it
      produces the start symbol. The semantic actions can raise
      exceptions. *)
  let apply (type a) tactic (env : a I.env) =
    let exception Accepted of a I.env in
    let rec go tactic env =
      let env = ref env in
      for i = tactic_offsets tactic to tactic_offsets (tactic + 1) - 1 do
        let a = tactic_actions i in
        let x = a / 4 in
        env := match a mod 4 with
          | 0 -> I.force_reduction (I.find_production x) !env
          | 1 -> shift x (position !env) !env
          | 2 -> go x !env
          | _ -> raise (Accepted !env)
      done;
      !env
    in
    match go tactic env with
    | env -> `Env env
    | exception (Accepted env) -> `Accept env

  (** Apply a tactic step by step, like Merlin: [`Steps envs], the
      configurations after each of its actions, a final call being
      expanded (it continues the item being completed); [`Accept env] if it
      accepts; [`Abort] if a semantic action fails. *)
  let apply_steps (type a) tactic (env : a I.env) =
    let exception Accepted of a I.env in
    let steps = ref [] in
    let rec go tactic env =
      let last = tactic_offsets (tactic + 1) - 1 in
      let env = ref env in
      for i = tactic_offsets tactic to last do
        let a = tactic_actions i in
        let x = a / 4 in
        match a mod 4 with
        | 2 when i = last -> env := go x !env
        | kind ->
          env := (match kind with
              | 0 -> I.force_reduction (I.find_production x) !env
              | 1 -> shift x (position !env) !env
              | 2 -> (match apply x !env with `Env e -> e | `Accept e -> raise (Accepted e))
              | _ -> raise (Accepted !env));
          steps := !env :: !steps
      done;
      !env
    in
    match go tactic env with
    | _ -> `Steps (List.rev !steps)
    | exception (Accepted env) -> `Accept env
    | exception _ -> `Abort

  (** The value of a parser that accepted: the semantic value at the top of
      its stack, which is the start symbol. *)
  let accepted (type a) (env : a I.env) : a =
    match I.top env with
    | Some (I.Element (_, v, _, _)) -> Obj.magic v
    | None -> assert false

  (** Merlin's decision for [env]: the tactic completing an item of its top
      state, chosen by the state at the depth of this state. *)
  let merlin_decision env =
    let top = I.current_state_number env in
    match merlin_default top with
    | 0 -> None
    | default ->
      let below = match I.pop_many (merlin_depth top) env with
        | None -> merlin_states
        | Some env -> I.current_state_number env
      in
      match lookup merlin_select (merlin_row top) below with
      | Some tactic -> Some tactic
      | None -> Some (default - 1)

  (** {1 Feeding tokens} *)

  type token = P.token * Lexing.position * Lexing.position

  (** Run the parser until it needs a token: [`Ok checkpoint], [`Error env],
      [`Raise (env, exn)] if a semantic action raises [exn], or
      [`Accept v]. A configuration
      of the recovery can accept before reading its token, by a default
      reduction: [`Accept] only counts after the token is shifted, the
      parser accepting the end of input. *)
  let feed (type a) (cp : a I.checkpoint)
    : [`Ok of a I.checkpoint | `Error of a I.env | `Raise of a I.env * exn
      | `Accept of a | `Early] =
    let shifted = ref false in
    let rec loop : a I.checkpoint -> _ = function
      | I.InputNeeded _ as cp -> `Ok cp
      | I.Shifting _ | I.AboutToReduce _ as cp ->
        (match cp with I.Shifting _ -> shifted := true | _ -> ());
        (match I.resume cp with
         | cp -> loop cp
         | exception exn -> `Raise ((match cp with
             | I.Shifting (env, _, _) | I.AboutToReduce (env, _) -> env
             | _ -> assert false), exn))
      | I.HandlingError env -> `Error env
      | I.Accepted v -> if !shifted then `Accept v else `Early
      | I.Rejected -> assert false
    in
    loop cp

  (** Offer a token to [env], and run until the parser needs another
      one: [`Error (env, Some exn)] if a semantic action raises [exn]. *)
  let offer env tok =
    match I.offer (I.input_needed env) tok with
    | cp -> (match feed cp with
        | `Error _ | `Early -> `Error (env, None)
        | `Raise (_, exn) -> `Error (env, Some exn)
        | (`Ok _ | `Accept _) as r -> r)
    | exception exn -> `Error (env, Some exn)

  (** {1 The input}

      The tokens are read as needed, and kept: a recovery can resume from
      an earlier token. *)

  type input = {
    mutable rest : token Seq.t;
    read : token Vec.t;
  }

  let input tokens = {rest = tokens; read = Vec.create ()}

  (* The token [i], if the input has one *)
  let rec get input i =
    if i < Vec.length input.read then Some (Vec.get input.read i)
    else match input.rest () with
      | Seq.Nil -> None
      | Seq.Cons (tok, rest) -> Vec.add_last input.read tok; input.rest <- rest; get input i

  let has input i = get input i <> None
  let token input i = Option.get (get input i)

  (** Whether [env] accepts the tokens [i] to [i + k - 1] (fewer at the end
      of input). *)
  let rec accepts env (get : int -> token option) i k =
    k = 0 ||
    match get i with
    | None -> true
    | Some tok ->
    match offer env tok with
    | `Ok (I.InputNeeded env') -> accepts env' get (i + 1) (k - 1)
    | `Ok _ -> assert false
    | `Accept _ -> true
    | `Error _ -> false

  (** {1 The simulated stack}

      The states of the stack, from the top, and the start and end offsets
      of its frames, with for the frames of the original stack of a
      recovery their number from the bottom, [0] for the frames
      synthesized by the recovery. *)

  module ET = MenhirLib.TableInterpreter.MakeEngineTable (P.Tables)

  let rec states env =
    I.current_state_number env :: (match I.pop env with None -> [] | Some env -> states env)

  let rec cells env =
    match I.top env with
    | None -> []
    | Some (I.Element (_, _, startp, endp)) ->
      (startp.Lexing.pos_cnum, endp.Lexing.pos_cnum) ::
      (match I.pop env with None -> [] | Some env -> cells env)

  exception Sim_accept

  (* The end of the top frame, where the parser places the frames of the
     empty productions and of the placeholders *)
  let top_end = function (_, e, _) :: _ -> e | [] -> Lexing.dummy_pos.pos_cnum

  (* The target of the goto transition of [state] on a non-terminal *)
  let goto state nt = ET.goto_nt state nt

  (* Pop [n] frames, and push the one of a symbol covering them, in the
     state [goto below] *)
  let sim_reduce n (states, cells) goto =
    let rec drop n states cells first =
      if n = 0 then (states, cells, first)
      else match states, cells with
        | _ :: states, (s, _, _) :: cells -> drop (n - 1) states cells (Some s)
        | _ -> raise Sim_accept
    in
    let states', cells', first = drop n states cells None in
    match states' with
    | below :: _ ->
      let cell = match first with
        | None -> (top_end cells, top_end cells, 0)
        | Some s -> (s, top_end cells, 0) in
      (goto below :: states', cell :: cells')
    | [] -> raise Sim_accept

  (* The stack after one action, and after a tactic *)
  let rec sim_action a stack =
    let x = a / 4 in
    match a mod 4 with
    | 0 ->
      sim_reduce (production_length x) stack (fun below -> ET.goto_prod below x)
    | 1 ->
      (match stack with
       | top :: _ as states, cells ->
         let p = top_end cells in
         let target =
           if x < terminal_count then
             (match ET.maybe_shift_t top x with Some s -> s | None -> raise Sim_accept)
           else goto top (x - terminal_count)
         in
         (target :: states, (p, p, 0) :: cells)
       | [], _ -> raise Sim_accept)
    | 2 -> sim_apply x stack
    | _ -> raise Sim_accept

  and sim_apply tactic stack =
    let stack = ref stack in
    for i = tactic_offsets tactic to tactic_offsets (tactic + 1) - 1 do
      stack := sim_action (tactic_actions i) !stack
    done;
    !stack

  (* The stacks after each step of a tactic, as [apply_steps] *)
  let sim_steps tactic stack =
    let steps = ref [] in
    let rec go tactic stack =
      let last = tactic_offsets (tactic + 1) - 1 in
      let stack = ref stack in
      for i = tactic_offsets tactic to last do
        let a = tactic_actions i in
        if a mod 4 = 2 && i = last then stack := go (a / 4) !stack
        else begin
          stack := sim_action a !stack;
          steps := !stack :: !steps
        end
      done;
      !stack
    in
    ignore (go tactic stack);
    List.rev !steps

  (* Whether the states [states] accept the tokens [j] to [j + k - 1], as
     [accepts] on the real stack, but without semantic actions (which can
     still fail): reading a token performs the default reductions, then
     looks up the action of the token *)
  let sim_accepts states (get : int -> token option) j k =
    let terminal i = match get i with
      | Some (tok, _, _) -> P.Tables.token2terminal tok
      | None -> assert false in
    (* [shifted]: a token was shifted, accepting is accepting it *)
    let rec read states j k shifted = k = 0 || get j = None || run states j k shifted
    and run states j k shifted =
      ET.default_reduction (List.hd states)
        (fun () prod -> reduce states prod j k shifted)
        (fun () -> action states j k shifted) ()
    and action states j k shifted =
      ET.action (List.hd states) (terminal j) (Obj.repr ())
        (fun () _ _ _ s' -> read (s' :: states) (j + 1) (k - 1) true)
        (fun () prod -> reduce states prod j k shifted)
        (fun () -> false) ()
    and reduce states prod j k shifted =
      if ET.is_start prod then shifted else
      let rec drop n l = if n = 0 then l else match l with _ :: l -> drop (n - 1) l | [] -> [] in
      match drop (production_length prod) states with
      | below :: _ as rest -> run (ET.goto_prod below prod :: rest) j k shifted
      | [] -> false
    in
    read states j k false

  (** {1 Brackets and spans} *)

  (** The policies, for the tokens of the parser (see [indentation] and
      [lexical] at the top of the module) *)
  type nonrec triple = P.token triple
  type nonrec bracket_policy = P.token bracket_policy
  let indentation : bracket_policy = indentation
  let lexical = lexical

  (* The spans of a policy: for each token, the innermost span containing
     it ([-1] for none); for each span, its parent, its start (its first
     token) and its end (the first token after it, the number of tokens
     while it is open). They are computed as needed, up to the last token
     queried: the spans that close later are still open. *)
  type spans = {
    input : input;
    innermost : int Vec.t;
    parent : int Vec.t;
    start : int Vec.t;
    finish : int Vec.t;
    mutable computed : int;
    mutable brackets : (int * int) Seq.t;
    mutable open_spans : int list;
  }

  let spans (policy : bracket_policy) input =
    let rec from i () =
      match get input i with
      | None -> Seq.Nil
      | Some (tok, s, e) -> Seq.Cons ((s, tok, e), from (i + 1))
    in
    {input; innermost = Vec.create (); parent = Vec.create ();
     start = Vec.create (); finish = Vec.create ();
     computed = 0; brackets = policy (from 0); open_spans = []}

  (* The end of the spans still open *)
  let still_open = max_int

  (* Compute the spans up to token [i] *)
  let extend sp i =
    while sp.computed <= i && has sp.input sp.computed do
      let i = sp.computed in
      (match sp.brackets () with
       | Seq.Nil -> sp.brackets <- Seq.empty
       | Seq.Cons ((opened, closed), rest) ->
         sp.brackets <- rest;
         for _ = 1 to closed do
           match sp.open_spans with
           | span :: others -> Vec.set sp.finish span i; sp.open_spans <- others
           | [] -> ()
         done;
         for _ = 1 to opened do
           let span = Vec.length sp.parent in
           Vec.add_last sp.parent (match sp.open_spans with p :: _ -> p | [] -> -1);
           Vec.add_last sp.start i;
           Vec.add_last sp.finish still_open;
           sp.open_spans <- span :: sp.open_spans
         done);
      Vec.add_last sp.innermost (match sp.open_spans with span :: _ -> span | [] -> -1);
      sp.computed <- i + 1
    done

  (* The number of spans computed *)
  let span_count sp = Vec.length sp.finish

  (* The token of an offset: the last one starting at or before it. The
     frames of the synthesized symbols and of the empty productions start
     where the previous frame ends, and belong to the token before. *)
  let token_index input cnum =
    let lo = ref 0 and hi = ref (Vec.length input.read - 1) in
    while !lo < !hi do
      let mid = (!lo + !hi + 1) / 2 in
      let _, s, _ = Vec.get input.read mid in
      if s.Lexing.pos_cnum <= cnum then lo := mid else hi := mid - 1
    done;
    !lo

  (* The first and last tokens of a frame; the last token of an empty frame
     is its first one *)
  let frame input (s, e) =
    let i = token_index input s in
    (i, if e <= s then i else max i (token_index input (e - 1)))

  (* The frames of [env], from the bottom *)
  let frame_tokens input env = List.rev_map (frame input) (cells env)

  (* The consistency of the frames with the spans. A frame violates the
     spans if a span closed before its start contains more than
     [1 + slack] frames below it (the parser accepted a token in a
     construct that the brackets had closed), or if it starts inside a
     span, after its first token, and ends after it (it absorbed tokens
     beyond a closed bracket). The frames are scanned from the bottom: the
     state of the scan is the number of frames in each span, and the
     earliest end of the spans holding too many frames; the counts only
     grow. *)

  let crosses sp s e =
    let rec go span = span >= 0 &&
      (Vec.get sp.start span < s && Vec.get sp.finish span <= e
       || go (Vec.get sp.parent span)) in
    s < Vec.length sp.innermost && go (Vec.get sp.innermost s)

  (* The first frame violating the spans, in [frames] from the bottom *)
  let violation ~slack sp frames =
    extend sp (List.fold_left (fun m (s, e) -> max m (max s e)) 0 frames);
    let count = Hashtbl.create 7 and min_bad = ref max_int in
    let rec scan k = function
      | [] -> None
      | (s, e) :: rest ->
        if crosses sp s e || !min_bad <= s then Some k else begin
          let rec up span =
            if span >= 0 then begin
              let c = 1 + Option.value (Hashtbl.find_opt count span) ~default:0 in
              Hashtbl.replace count span c;
              if c > 1 + slack then min_bad := min !min_bad (Vec.get sp.finish span);
              up (Vec.get sp.parent span)
            end
          in
          if s < Vec.length sp.innermost then up (Vec.get sp.innermost s);
          scan (k + 1) rest
        end
    in
    scan 0 frames

  (* The scan of the frames of the original stack of a recovery, once for
     each token [j]: after [l] frames, whether a violation was found, and
     the earliest end of a span holding too many frames *)
  let prefix_scan ~slack sp root j =
    extend sp (Array.fold_left (fun m (s, e) -> max m (max s e)) j root);
    let r = Array.length root in
    let bad = Array.make (r + 1) false and min_bad = Array.make (r + 1) max_int in
    let count = Hashtbl.create 16 in
    Array.iteri (fun k (s, e) ->
        bad.(k + 1) <- bad.(k) || crosses sp s e || min_bad.(k) <= s;
        min_bad.(k + 1) <- min_bad.(k);
        let rec up span =
          if span >= 0 then begin
            let c = 1 + Option.value (Hashtbl.find_opt count span) ~default:0 in
            Hashtbl.replace count span c;
            if c > 1 + slack then min_bad.(k + 1) <- min min_bad.(k + 1) (Vec.get sp.finish span);
            up (Vec.get sp.parent span)
          end
        in
        if s < Vec.length sp.innermost then up (Vec.get sp.innermost s))
      root;
    (bad, min_bad)

  (** {1 The search} *)

  (* A binary heap of values by priority, the first pushed first among
     equal priorities *)
  module Heap = struct
    let less (p1, c1) (p2, c2) = p1 < p2 || (p1 = p2 && c1 < c2)
    type 'a t = {mutable keys : (int * int) array; mutable values : 'a array; mutable size : int}
    let create () = {keys = [||]; values = [||]; size = 0}
    let swap h i j =
      let k = h.keys.(i) and v = h.values.(i) in
      h.keys.(i) <- h.keys.(j); h.values.(i) <- h.values.(j);
      h.keys.(j) <- k; h.values.(j) <- v
    let push h key v =
      if h.size = Array.length h.keys then begin
        let cap = max 16 (2 * h.size) in
        h.keys <- Array.append h.keys (Array.make (cap - h.size) (0, 0));
        h.values <- Array.append h.values (Array.make (cap - h.size) v)
      end;
      h.keys.(h.size) <- key; h.values.(h.size) <- v;
      let rec up i =
        let p = (i - 1) / 2 in
        if i > 0 && less h.keys.(i) h.keys.(p) then (swap h i p; up p)
      in
      up h.size;
      h.size <- h.size + 1
    let top h = if h.size = 0 then None else Some h.keys.(0)
    let clear h = h.size <- 0
    let pop h =
      if h.size = 0 then None else begin
        let v = h.values.(0) in
        h.size <- h.size - 1;
        h.keys.(0) <- h.keys.(h.size); h.values.(0) <- h.values.(h.size);
        let rec down i =
          let l = 2 * i + 1 and r = 2 * i + 2 in
          let m = if l < h.size && less h.keys.(l) h.keys.(i) then l else i in
          let m = if r < h.size && less h.keys.(r) h.keys.(m) then r else m in
          if m <> i then (swap h i m; down m)
        in
        down 0;
        Some v
      end
  end

  (** Statistics of the recovery. *)
  type stats = {
    mutable recoveries : int; (** the errors recovered from *)
    mutable repairs : int; (** the stacks cut at a violation *)
    mutable skipped : int; (** the tokens skipped *)
    mutable expansions : int; (** the configurations expanded *)
    mutable mismatches : int; (** with [~verify], the differences between
                                  the simulation and the parser *)
  }

  let stats () = {recoveries = 0; repairs = 0; skipped = 0; expansions = 0; mismatches = 0}

  (* A candidate: its simulated stack, its cost, the number of symbols it
     synthesized, and its real stack, built when needed ([None] if a
     semantic action raises) *)
  type 'a sim = {
    states : int list;
    cells : (int * int * int) list;
    s_cost : int;
    s_shifts : int;
    real : 'a I.env option Lazy.t;
  }

  (* The number of symbols a tactic shifts *)
  let tactic_shifts =
    let table = Hashtbl.create 64 in
    let rec count t =
      match Hashtbl.find_opt table t with
      | Some n -> n
      | None ->
        let n = ref 0 in
        for i = T.tactic_offsets t to T.tactic_offsets (t + 1) - 1 do
          let a = T.tactic_actions i in
          match a land 3 with
          | 1 -> incr n
          | 2 -> n := !n + count (a lsr 2)
          | _ -> ()
        done;
        Hashtbl.add table t !n;
        !n
    in
    count

  (* The priority of a candidate: its cost, then, at the same cost, the
     fewest symbols synthesized, the rest of the cost going to reductions
     (completing [x] rather than inventing [x <- _]) *)
  let priority cost shifts = cost * 4096 + min shifts 4095

  (* A configuration is identified by the states of its synthesized frames
     and the number of frames it shares with the original stack *)
  let sim_key sim =
    let rec go states cells acc =
      match states, cells with
      | st :: states, (_, _, 0) :: cells -> go states cells (st :: acc)
      | _, (_, _, k) :: _ -> (acc, k)
      | _, [] -> (acc, 0)
    in
    go sim.states sim.cells []

  (* The value of an accepting configuration: following the cheapest
     strategy whose semantic actions do not raise, and that does not come
     back to a configuration of the chain (the strategies after the
     cheapest one can keep the height of the stack); when all of them
     raise, the top frame is dropped *)
  let complete env =
    let height env =
      let rec loop env n = match I.pop env with None -> n | Some env -> loop env (n + 1) in
      loop env 0
    in
    let visited = Hashtbl.create 7 in
    let rec chain env =
      Hashtbl.replace visited (I.current_state_number env, height env) ();
      let rec first = function
        | [] -> (match I.pop env with Some env' -> chain env' | None -> None)
        | {tactic; _} :: rest ->
          match apply tactic env with
          | `Env env' when Hashtbl.mem visited (I.current_state_number env', height env') -> first rest
          | `Env env' -> chain env'
          | `Accept env' -> Some (accepted env')
          | exception _ -> first rest
      in
      first (strategies env)
    in
    chain env

  (* The search from [env], simulated on its states: a generator of the
     candidates by increasing cost, the configurations reached by the
     strategies (expanding [limit] of them) and, with [steps], the
     configurations inside the cheapest strategy of each one, which are
     not expanded; and the value of the cheapest accepting
     configuration. *)
  let search ~limit ~steps ~stats ~verify env =
    let seen = Hashtbl.create 7 and finals = ref [] in
    let check (states', cells') real =
      (match real with
       | Some env when verify &&
                       (states env <> states' ||
                        cells env <> List.map (fun (s, e, _) -> (s, e)) cells') ->
         stats.mismatches <- stats.mismatches + 1
       | _ -> ());
      real
    in
    (* The configurations to expand, and the inner candidates, which share
       the order of discovery *)
    let queue = Heap.create () and inner = Heap.create () in
    let counter = ref 0 in
    (* The least cost at which each configuration was pushed: a later push
       at a cost no lower would be popped after, and dropped *)
    let best = Hashtbl.create 64 in
    let push cost shifts x =
      incr counter;
      let p = priority cost shifts in
      match x with
      | `Expand sim ->
        let key = sim_key sim in
        (match Hashtbl.find_opt best key with
         | Some p' when p' <= p -> ()
         | _ -> Hashtbl.replace best key p; Heap.push queue (p, !counter) x)
      | `Inner _ -> Heap.push inner (p, !counter) x
    in
    let root_cells = let l = cells env in let r = List.length l in List.mapi (fun i (s, e) -> (s, e, r - i)) l in
    push 0 0 (`Expand {states = states env; cells = root_cells; s_cost = 0; s_shifts = 0;
                       real = lazy (Some env)});
    let expansions = ref 0 in
    let final_value sim tactic = lazy (match Lazy.force sim.real with
        | None -> None
        | Some e -> match apply tactic e with
          | `Accept e -> Some (accepted e)
          | `Env _ -> None
          | exception _ -> None) in
    let expand sim =
      List.iteri (fun k {tactic; cost = c; lhs; pos; _} ->
          let cost = sim.s_cost + c and shifts = sim.s_shifts + tactic_shifts tactic in
          if steps && k = 0 then
            (match sim_steps tactic (sim.states, sim.cells) with
             | exception Sim_accept ->
               finals := (priority cost shifts, final_value sim tactic) :: !finals
             | steps_states ->
               (* The real configurations of the steps, shared by them *)
               let real_steps = lazy (match Lazy.force sim.real with
                   | None -> None
                   | Some e -> match apply_steps tactic e with
                     | `Steps envs -> Some (Array.of_list envs)
                     | _ -> None) in
               let nth i = lazy (match Lazy.force real_steps with
                   | Some a when i < Array.length a -> Some a.(i)
                   | _ -> None) in
               let n = List.length steps_states in
               List.iteri (fun i (states, cells as stack) ->
                   let real = nth i in
                   let real = lazy (check stack (Lazy.force real)) in
                   if i < n - 1 then
                     let c' = sim.s_cost + min c (i + 1)
                     and shifts' = sim.s_shifts + min (shifts - sim.s_shifts) (i + 1) in
                     push c' shifts'
                       (`Inner {states; cells; s_cost = c'; s_shifts = shifts'; real})
                   else push cost shifts (`Expand {states; cells; s_cost = cost; s_shifts = shifts; real}))
                 steps_states)
          else
            (* A strategy completes an item: it pops [pos] frames and
               follows the goto transition of [lhs] *)
            match
              if lhs < 0 then raise Sim_accept;
              sim_reduce pos (sim.states, sim.cells) (fun below -> goto below lhs)
            with
            | exception Sim_accept ->
              finals := (priority cost shifts, final_value sim tactic) :: !finals
            | (states, cells) as stack ->
              let real = lazy (match Lazy.force sim.real with
                  | None -> None
                  | Some e -> match apply tactic e with
                    | `Env e -> check stack (Some e)
                    | `Accept _ -> None
                    | exception _ -> None) in
              push cost shifts (`Expand {states; cells; s_cost = cost; s_shifts = shifts; real}))
        (match sim.states with
         | top :: below :: _ -> strategies_of_states top (Some below)
         | [top] -> strategies_of_states top None
         | [] -> [])
    in
    let rec next () =
      if !expansions >= limit then Heap.clear queue;
      let from = match Heap.top queue, Heap.top inner with
        | None, None -> None
        | Some _, None -> Some queue
        | None, Some _ -> Some inner
        | Some k1, Some k2 -> Some (if Heap.less k2 k1 then inner else queue)
      in
      match Option.bind from Heap.pop with
      | None -> None
      | Some (`Inner c) -> Some c
      | Some (`Expand sim) ->
        let key = sim_key sim in
        if Hashtbl.mem seen key then next () else begin
          Hashtbl.add seen key ();
          incr expansions;
          stats.expansions <- stats.expansions + 1;
          expand sim;
          Some sim
        end
    in
    (* The cheapest accepting configuration whose semantic actions succeed,
       after the search *)
    let final () =
      let rec drain () = match next () with None -> () | Some _ -> drain () in
      drain ();
      let rec first = function
        | [] -> complete env
        | (_, v) :: rest -> match Lazy.force v with Some v -> Some v | None -> first rest
      in
      first (List.stable_sort (fun (c1, _) (c2, _) -> compare c1 c2) (List.rev !finals))
    in
    next, final

  let feed_checkpoint = feed

  (** {1 Policies} *)

  (** A policy: a fold over the tokens given to a recovery, which tells, at
      each token, the number of frames of the stack of the recovery, from
      the bottom, that may still be open when this token is shifted. *)
  type 's policy = {
    state : 's;
    feed : 's -> token -> 's * int;
  }

  (** A guide: the cut it advises at an error, and the policy of a recovery
      from a stack. *)
  type 's guide = {
    cut : 'a. 'a I.env -> ('a I.env * Lexing.position) option;
    start : 'a. 'a I.env -> 's policy;
  }

  (* The start and end positions of the frames of [env], from the bottom *)
  let positions env =
    let rec go env acc =
      match I.top env with
      | None -> acc
      | Some (I.Element (_, _, s, e)) ->
        let acc = (s, e) :: acc in
        match I.pop env with None -> acc | Some env -> go env acc
    in
    Array.of_list (go env [])

  let column (p : Lexing.position) = p.pos_cnum - p.pos_bol

  (** {2 Frames} *)

  (* The indentation of the frames, from the bottom: the column of a frame
     that starts a line, the indentation of the frame below otherwise *)
  let starts_line fr k =
    k = 0 || (fst fr.(k)).Lexing.pos_lnum > (snd fr.(k - 1)).Lexing.pos_lnum

  let indentations fr =
    let ind = Array.make (Array.length fr) 0 in
    Array.iteri (fun k (s, _) ->
        ind.(k) <- if starts_line fr k then column s else ind.(k - 1))
      fr;
    ind

  (* The frames, among the [n] first ones, that a line at column [t] closes:
     the first frame of the first run of frames more indented than [t]
     holding more than [1 + slack] of them ([n] for none). These frames
     cannot stay open: the run should have been reduced. *)
  let closing ~slack ind n t =
    let result = ref n and run = ref 0 and k = ref 0 in
    while !k < n && !result = n do
      if ind.(!k) > t then begin
        incr run;
        if !run > 1 + slack then result := !k + 1 - !run
      end else run := 0;
      incr k
    done;
    !result

  type frames = {
    indent : int array;
    slack : int;
    last_line : int;
    open_frames : int;
  }

  let frames ?(slack = 0) () = {
    cut = (fun env ->
        let fr = positions env in
        let ind = indentations fr in
        let n = Array.length fr in
        let rec find k =
          if k >= n then None
          else if starts_line fr k && closing ~slack ind k (column (fst fr.(k))) < k
          then Some k
          else find (k + 1)
        in
        match find 1 with
        | None -> None
        | Some k -> Option.map (fun env' -> (env', fst fr.(k))) (I.pop_many (n - k) env));
    start = (fun env ->
        let fr = positions env in
        let n = Array.length fr in
        let last_line = if n = 0 then 0 else (snd fr.(n - 1)).pos_lnum in
        {state = {indent = indentations fr; slack; last_line; open_frames = n};
         feed = (fun st (_, s, e) ->
             let open_frames =
               if s.pos_lnum > st.last_line
               then closing ~slack:st.slack st.indent st.open_frames (column s)
               else st.open_frames
             in
             ({st with last_line = e.pos_lnum; open_frames}, open_frames))});
  }

  (** {2 Brackets} *)

  (* Read the input past the tokens starting at or before [cnum] *)
  let read_past input cnum =
    let rec go i =
      match get input i with
      | Some (_, s, _) when s.Lexing.pos_cnum <= cnum -> go (i + 1)
      | _ -> ()
    in
    go (max 0 (Vec.length input.read - 1))

  let top_cnum env =
    match I.top env with
    | Some (I.Element (_, _, _, e)) -> e.Lexing.pos_cnum
    | None -> 0

  let brackets ?(slack = 0) (policy : bracket_policy) tokens =
    let sp = spans policy (input tokens) in
    let input = sp.input in
    {
      cut = (fun env ->
          read_past input (top_cnum env);
          let fs = frame_tokens input env in
          let n = List.length fs in
          (* The frames and the token after them, where the parser failed *)
          let next = 1 + List.fold_left (fun m (s, e) -> max m (max s e)) (-1) fs in
          match violation ~slack sp (fs @ [(next, next)]) with
          | Some k when k < n ->
            Option.map (fun env' -> (env', fst (positions env).(k))) (I.pop_many (n - k) env)
          | _ -> None);
      start = (fun env ->
          read_past input (top_cnum env);
          let root = Array.of_list (frame_tokens input env) in
          let r = Array.length root in
          {state = r;
           feed = (fun open_frames (_, s, _) ->
               read_past input s.pos_cnum;
               let j = token_index input s.pos_cnum in
               let bad, min_bad = prefix_scan ~slack sp root j in
               let rec go l =
                 if l < r && not bad.(l + 1) && min_bad.(l + 1) > j then go (l + 1) else l in
               let o = min open_frames (go 0) in
               (o, o))});
    }

  (** {1 The recovery} *)

  type 'a recovery = {
    r_limit : int;
    r_lookahead : int;
    r_steps : bool;
    r_verify : bool;
    r_stats : stats;
    r_log : string -> unit;
    feed_policy : token -> int;
    (* The stack the candidates are built from, and the search *)
    mutable base : 'a I.env;
    mutable next : unit -> 'a sim option;
    mutable final : unit -> 'a option;
    mutable generated : 'a sim Vec.t;
    mutable exhausted : bool;
    (* Whether candidate [k] accepts a terminal (a byte per terminal) *)
    mutable first : Bytes.t Vec.t;
    (* The tokens fed, not yet consumed, with their number of open frames *)
    mutable pending : (token * int) list;
  }

  let restart r env =
    let next, final =
      search ~limit:r.r_limit ~steps:r.r_steps ~stats:r.r_stats ~verify:r.r_verify env in
    r.base <- env; r.next <- next; r.final <- final;
    r.generated <- Vec.create (); r.exhausted <- false; r.first <- Vec.create ()

  let recover ?(limit = 100) ?(lookahead = 3) ?(steps = true) ?(verify = false)
      ?(stats = stats ()) ?log policy env =
    stats.recoveries <- stats.recoveries + 1;
    let state = ref policy.state in
    let feed_policy tok = let s, o = policy.feed !state tok in state := s; o in
    let r = {
      r_limit = limit; r_lookahead = max 1 lookahead; r_steps = steps; r_verify = verify;
      r_stats = stats; r_log = Option.value log ~default:ignore; feed_policy;
      base = env; next = (fun () -> None); final = (fun () -> None);
      generated = Vec.create (); exhausted = false; first = Vec.create ();
      pending = [];
    } in
    restart r env;
    r

  (* The candidates, generated as needed by increasing cost *)
  let rec nth r k =
    if k < Vec.length r.generated then Some (Vec.get r.generated k)
    else if r.exhausted then None
    else match r.next () with
      | None -> r.exhausted <- true; None
      | Some c -> Vec.add_last r.generated c; nth r k

  (* The number of frames of the original stack a candidate keeps *)
  let kept c =
    let rec go = function
      | (_, _, k) :: _ when k > 0 -> k
      | _ :: rest -> go rest
      | [] -> 0
    in
    go c.cells

  (* Choose the candidate that resumes at the first token of [window], and
     feed it the tokens of the window: [`Resume env], [`Accept v], or
     [`Skip] if no candidate accepts the first token *)
  let rec decide r window =
    let tokens = Array.of_list (List.map fst window) in
    let get i = if i < Array.length tokens then Some tokens.(i) else None in
    let open_frames = snd (List.hd window) in
    let accepts_first k c =
      while Vec.length r.first <= k do Vec.add_last r.first (Bytes.make terminal_count '?') done;
      let cache = Vec.get r.first k in
      let tok, _, _ = tokens.(0) in
      let t = P.Tables.token2terminal tok in
      match Bytes.get cache t with
      | 'y' -> true
      | 'n' -> false
      | _ ->
        let b = sim_accepts c.states get 0 1 in
        Bytes.set cache t (if b then 'y' else 'n');
        b
    in
    let real_accepts real =
      match Lazy.force real with
      | Some env when accepts env get 0 r.r_lookahead -> Some env
      | _ -> None
    in
    let rec first_real = function
      | [] -> None
      | real :: rest ->
        match real_accepts real with Some env -> Some env | None -> first_real rest
    in
    (* The cheapest accepting candidate that keeps at most [open_frames]
       frames; the cheapest accepting one if none does, as skipping tokens
       cannot close the frames. The candidates are tried on their simulated
       stack, the real one being built for the candidate chosen, whose
       semantic actions can still fail. *)
    let n_real = ref 0 in
    let rec scan k fallbacks =
      match nth r k with
      | None -> first_real (List.rev fallbacks)
      | Some c ->
        let accepted = accepts_first k c && sim_accepts c.states get 0 r.r_lookahead in
        if r.r_verify && not accepted then
          (match Lazy.force c.real with
           | Some env when accepts env get 0 r.r_lookahead ->
             r.r_stats.mismatches <- r.r_stats.mismatches + 1
           | _ -> ());
        if not accepted then scan (k + 1) fallbacks
        else if kept c <= open_frames then
          match real_accepts c.real with
          | Some env -> Some env
          | None -> incr n_real; scan (k + 1) fallbacks
        else scan (k + 1) (c.real :: fallbacks)
    in
    match scan 0 [] with
    | None when !n_real > 0 && Option.is_some (I.pop r.base) ->
      (* Candidates accept the token, but the semantic actions of their
         tactics fail: the frame they complete is dropped, as by [complete],
         and the recovery resumes below it *)
      r.r_log "dropping the top frame";
      restart r (Option.get (I.pop r.base));
      decide r window
    | None -> `Skip
    | Some env ->
      let rec go env = function
        | [] -> `Resume env
        | (tok, _) :: rest ->
          match offer env tok with
          | `Ok (I.InputNeeded env') -> go env' rest
          | `Ok _ -> assert false
          | `Accept v -> `Accept v
          | `Error _ -> `Skip
      in
      go env window

  let skip r =
    r.r_stats.skipped <- r.r_stats.skipped + 1;
    r.pending <- List.tl r.pending

  let feed r tok =
    r.pending <- r.pending @ [(tok, r.feed_policy tok)];
    if List.length r.pending < r.r_lookahead then `Recovering
    else match decide r r.pending with
      | `Skip -> r.r_log "skipping a token"; skip r; `Recovering
      | `Resume env -> r.r_log "resuming"; `Resume env
      | `Accept v -> `Accept v

  let rec finish r =
    match r.pending with
    | [] -> r.final ()
    | window ->
      match decide r window with
      | `Skip -> skip r; finish r
      | `Accept v -> Some v
      | `Resume env ->
        let _, final =
          search ~limit:r.r_limit ~steps:r.r_steps ~stats:r.r_stats ~verify:r.r_verify env in
        final ()

  (** {1 Parsing with recovery} *)

  let input_seq input =
    let rec from i () =
      match get input i with
      | None -> Seq.Nil
      | Some t -> Seq.Cons (t, from (i + 1))
    in
    from 0

  let parse_input ~limit ~lookahead ~steps ~verify ~stats ~log ~on_error
      ~on_exception ~repair guide (entry : 'a I.checkpoint) input =
    let logf fmt = Printf.ksprintf (fun s -> match log with Some f -> f s | None -> ()) fmt in
    let line i = match get input i with Some (_, p, _) -> p.Lexing.pos_lnum | None -> -1 in
    let last_repair = ref (-1) and last_error = ref (-1) in
    (* The first token, before [i], starting at or after [p] *)
    let index_at (p : Lexing.position) i =
      let lo = ref 0 and hi = ref i in
      while !lo < !hi do
        let mid = (!lo + !hi) / 2 in
        let _, s, _ = token input mid in
        if s.pos_cnum < p.pos_cnum then lo := mid + 1 else hi := mid
      done;
      !lo
    in
    let rec normal (cp : 'a I.checkpoint) i : 'a option =
      match cp with
      | I.InputNeeded env ->
        (match get input i with
         | None -> logf "the input ends at token %d" i; recover_at env i
         | Some tok ->
           match offer env tok with
           | `Ok cp' -> normal cp' (i + 1)
           | `Accept v -> logf "accepted at token %d (line %d)" i (line i); Some v
           | `Error (_, exn) ->
             logf "error at token %d (line %d)" i (line i);
             (* A repair resumes from an earlier token, and can meet the
                same error again: it is reported once *)
             if i > !last_error then begin
               last_error := i;
               match exn, on_exception, on_error with
               | Some exn, Some f, _ -> f env tok exn
               | _, _, Some f -> f env tok
               | _ -> ()
             end;
             recover_at env i)
      | _ -> assert false
    and recover_at (env : 'a I.env) i : 'a option =
      (* The cut advised by the guide: each one must start after the
         previous one, for the parse to progress *)
      let env, i =
        if not repair then (env, i) else
          match guide.cut env with
          | Some (env', p) ->
            let k = index_at p i in
            if k > !last_repair then begin
              last_repair := k;
              stats.repairs <- stats.repairs + 1;
              logf "repair: resuming at token %d (line %d)" k (line k);
              (env', k)
            end else (env, i)
          | None -> (env, i)
      in
      let r = recover ~limit ~lookahead ~steps ~verify ~stats ?log (guide.start env) env in
      let rec loop j =
        match get input j with
        | None -> logf "completing at the end of input (token %d)" j; finish r
        | Some tok ->
          match feed r tok with
          | `Recovering -> loop (j + 1)
          | `Resume env ->
            logf "resumed, at token %d (line %d)" (j + 1) (line (j + 1));
            normal (I.input_needed env) (j + 1)
          | `Accept v -> Some v
      in
      loop i
    in
    match feed_checkpoint entry with
    | `Ok cp -> normal cp 0
    | `Accept _ | `Early | `Error _ | `Raise _ -> None

  let parse ?(limit = 100) ?(lookahead = 3) ?(steps = true) ?(verify = false) ?(repair = true)
      ?(stats = stats ()) ?log ?on_error ?on_exception policy entry (tokens : token Seq.t) =
    let input = input tokens in
    parse_input ~limit ~lookahead ~steps ~verify ~stats ~log ~on_error ~on_exception ~repair
      (policy (input_seq input)) entry input

  let tokens_of_supplier ~is_eof (supplier : unit -> token) : token Seq.t =
    let rec next ended () =
      if ended then Seq.Nil else
        let (tok, _, _) as t = supplier () in
        Seq.Cons (t, next (is_eof tok))
    in
    next false

  let parse_supplier ?limit ?lookahead ?steps ?verify ?repair ?stats ?log ?on_error ?on_exception
      ~is_eof policy entry supplier =
    parse ?limit ?lookahead ?steps ?verify ?repair ?stats ?log ?on_error ?on_exception policy entry
      (tokens_of_supplier ~is_eof supplier)

  let parse_lexbuf ?limit ?lookahead ?steps ?verify ?repair ?stats ?log ?on_error ?on_exception
      ~is_eof policy entry lexer lexbuf =
    parse_supplier ?limit ?lookahead ?steps ?verify ?repair ?stats ?log ?on_error ?on_exception
      ~is_eof policy entry
      (I.lexer_lexbuf_to_supplier lexer lexbuf)
end
